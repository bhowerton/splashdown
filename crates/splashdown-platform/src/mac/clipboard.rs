//! Pasteboard snapshot/restore, paste and typing via synthetic key events,
//! and the copy-based selection fallback.

use std::sync::Mutex;
use std::sync::atomic::{AtomicU16, AtomicU64, Ordering};
use std::time::{Duration, Instant};

use core_foundation::base::{CFRelease, TCFType};
use core_foundation::data::{CFData, CFDataRef};

use core_graphics::event::{CGEvent, CGEventFlags, CGEventTapLocation, CGKeyCode, EventField};
use core_graphics::event_source::{CGEventSource, CGEventSourceStateID};
use objc2::MainThreadMarker;
use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSPasteboard, NSPasteboardItem, NSPasteboardType, NSPasteboardTypeString, NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSString};

use crate::{PlatformError, Result};

/// How long to wait after Cmd+V before carrying on (pressing Return, say).
const PASTE_SETTLE: Duration = Duration::from_millis(150);
/// When the user's clipboard is put back after a paste. Apps read the
/// pasteboard asynchronously; too soon and they paste the old contents.
const RESTORE_AFTER: Duration = Duration::from_millis(1000);
/// How long to wait for Cmd+C to update the pasteboard.
const COPY_TIMEOUT: Duration = Duration::from_millis(150);

/// Markers that tell clipboard managers to ignore our temporary contents
/// (nspasteboard.org conventions).
const TRANSIENT_TYPES: &[&str] = &[
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

/// Key codes for Cmd+C/V/Z on the current keyboard layout, looked up by
/// `refresh_shortcut_keys` (ANSI codes until then, or if it fails).
static KEY_C: AtomicU16 = AtomicU16::new(0x08);
static KEY_V: AtomicU16 = AtomicU16::new(0x09);
static KEY_Z: AtomicU16 = AtomicU16::new(0x06);
static KEY_B: AtomicU16 = AtomicU16::new(0x0B);
static KEY_I: AtomicU16 = AtomicU16::new(0x22);
const KEY_RETURN: CGKeyCode = 0x24;
const KEY_DELETE: CGKeyCode = 0x33;
const KEY_RIGHT: CGKeyCode = 0x7C;

/// Finds which keys type "c", "v", "z", "b" and "i" with Command held on
/// the current layout (e.g. Dvorak), so synthetic shortcuts hit the right command.
/// Layouts like "Dvorak – QWERTY ⌘" switch to QWERTY under Command, which
/// translating with the Command modifier handles. Main thread only.
pub(crate) fn refresh_shortcut_keys() {
    use super::ffi;
    const KEY_ACTION_DISPLAY: u16 = 3;
    const CMD_MODIFIER: u32 = 1; // (cmdKey >> 8) & 0xFF
    const NO_DEAD_KEYS: u32 = 1;

    // Text Input Sources assert they're on the main queue on recent macOS.
    if MainThreadMarker::new().is_none() {
        tracing::warn!("refresh_shortcut_keys called off the main thread; skipped");
        return;
    }
    // SAFETY: no arguments, and we're on the main thread (checked above).
    // Returns a +1 reference (Copy rule) or null; released at the end.
    let source = unsafe { ffi::TISCopyCurrentKeyboardLayoutInputSource() };
    if source.is_null() {
        return;
    }
    // SAFETY: `source` is a live input source and the key a framework
    // constant. The result follows the Get rule: owned by `source`.
    let data =
        unsafe { ffi::TISGetInputSourceProperty(source, ffi::kTISPropertyUnicodeKeyLayoutData) };
    if !data.is_null() {
        // SAFETY: this property is documented to be a CFDataRef; the Get rule
        // wrapper retains it, so it outlives `source` if need be.
        let data = unsafe { CFData::wrap_under_get_rule(data as CFDataRef) };
        // Points into `data`, which stays alive until the end of this block.
        let layout = data.bytes().as_ptr().cast();
        // SAFETY: no arguments; returns the current keyboard type.
        let kbd_type = u32::from(unsafe { ffi::LMGetKbdType() });
        let mut found = [None::<u16>; 5];
        for code in 0u16..128 {
            let mut dead = 0u32;
            let mut len = 0usize;
            let mut buf = [0u16; 4];
            // SAFETY: `layout` points to the UCKeyboardLayout held by the
            // live `data`; `dead` and `len` are valid out-pointers, and `buf`
            // has room for the `buf.len()` UTF-16 units we allow.
            let status = unsafe {
                ffi::UCKeyTranslate(
                    layout,
                    code,
                    KEY_ACTION_DISPLAY,
                    CMD_MODIFIER,
                    kbd_type,
                    NO_DEAD_KEYS,
                    &mut dead,
                    buf.len(),
                    &mut len,
                    buf.as_mut_ptr(),
                )
            };
            if status != 0 || len != 1 {
                continue;
            }
            let slot = match char::from_u32(u32::from(buf[0])).map(|c| c.to_ascii_lowercase()) {
                Some('c') => 0,
                Some('v') => 1,
                Some('z') => 2,
                Some('b') => 3,
                Some('i') => 4,
                _ => continue,
            };
            found[slot].get_or_insert(code);
        }
        for (slot, key) in [&KEY_C, &KEY_V, &KEY_Z, &KEY_B, &KEY_I]
            .into_iter()
            .enumerate()
        {
            if let Some(code) = found[slot] {
                key.store(code, Ordering::Relaxed);
            }
        }
        tracing::debug!(
            "shortcut keys: c={:?} v={:?} z={:?} b={:?} i={:?}",
            found[0],
            found[1],
            found[2],
            found[3],
            found[4]
        );
    }
    // SAFETY: balances the Copy above; `source` isn't used again, and `data`
    // holds its own retain.
    unsafe { CFRelease(source) };
}

/// Everything on the pasteboard, item by item and type by type.
struct Snapshot(Vec<Vec<(Retained<NSPasteboardType>, Retained<NSData>)>>);

fn general() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

fn snapshot(pb: &NSPasteboard) -> Snapshot {
    let mut items = Vec::new();
    if let Some(pb_items) = pb.pasteboardItems() {
        for item in pb_items.iter() {
            let mut entries = Vec::new();
            for ty in item.types().iter() {
                if let Some(data) = item.dataForType(&ty) {
                    entries.push((ty.clone(), data));
                }
            }
            items.push(entries);
        }
    }
    Snapshot(items)
}

fn restore(pb: &NSPasteboard, snap: &Snapshot) {
    pb.clearContents();
    if snap.0.is_empty() {
        return;
    }
    let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = snap
        .0
        .iter()
        .map(|entries| {
            let item = NSPasteboardItem::new();
            for (ty, data) in entries {
                item.setData_forType(data, ty);
            }
            ProtocolObject::from_retained(item)
        })
        .collect();
    pb.writeObjects(&NSArray::from_retained_slice(&items));
}

/// Writes `text` as the only pasteboard contents. `transient` marks it so
/// clipboard managers skip it.
fn write_text(pb: &NSPasteboard, text: &str, transient: bool) -> bool {
    pb.clearContents();
    // SAFETY: reads an immutable constant exported by AppKit.
    let ok = pb.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
    if transient {
        let empty = NSData::new();
        for ty in TRANSIENT_TYPES {
            pb.setData_forType(Some(&empty), &NSString::from_str(ty));
        }
    }
    ok
}

/// The text on the clipboard, if any (for a preset's clipboard context).
pub(crate) fn clipboard_text() -> Option<String> {
    read_text(&general())
}

fn read_text(pb: &NSPasteboard) -> Option<String> {
    // SAFETY: reads an immutable constant exported by AppKit.
    pb.stringForType(unsafe { NSPasteboardTypeString })
        .map(|s| s.to_string())
}

fn source() -> Result<CGEventSource> {
    // A private source, so modifiers the user is physically holding don't
    // leak into our synthetic events.
    CGEventSource::new(CGEventSourceStateID::Private)
        .map_err(|_| PlatformError::Failed("couldn't create event source".into()))
}

/// Shift, Control, Option, Command and Fn.
const MODIFIER_MASK: u64 = 0x0002_0000 | 0x0004_0000 | 0x0008_0000 | 0x0010_0000 | 0x0080_0000;
const HID_SYSTEM_STATE: i32 = 1;

/// Waits (briefly) until the user lets go of physical modifier keys, so a
/// synthetic Cmd+V isn't seen as Cmd+Ctrl+Option+V by apps that read the
/// live keyboard state, e.g. right after a ⌃⌥V shortcut.
fn wait_for_modifiers_released() {
    let deadline = Instant::now() + Duration::from_millis(800);
    while Instant::now() < deadline {
        // SAFETY: plain value argument (a valid CGEventSourceStateID) and
        // no other preconditions.
        let flags = unsafe { super::ffi::CGEventSourceFlagsState(HID_SYSTEM_STATE) };
        if flags & MODIFIER_MASK == 0 {
            return;
        }
        std::thread::sleep(Duration::from_millis(15));
    }
}

/// Marks our synthetic events, so our own key listener ignores them
/// ("SPLD", as on Windows).
pub(crate) const INJECTED_TAG: i64 = 0x5350_4C44;
/// Between the key events of a shortcut. Chrome drops a ⌘V whose events
/// arrive all at once, especially while it's busy.
const KEY_GAP: Duration = Duration::from_millis(12);
const KEY_COMMAND: CGKeyCode = 0x37;
const KEY_OPTION: CGKeyCode = 0x3A;

/// Presses `key` with `flags` the way a person does: modifiers down, the
/// key down and up, modifiers up, with short gaps.
fn post_key(key: CGKeyCode, flags: CGEventFlags) -> Result<()> {
    wait_for_modifiers_released();
    let modifiers: Vec<(CGKeyCode, CGEventFlags)> = [
        (KEY_COMMAND, CGEventFlags::CGEventFlagCommand),
        (KEY_OPTION, CGEventFlags::CGEventFlagAlternate),
    ]
    .into_iter()
    .filter(|(_, f)| flags.contains(*f))
    .collect();
    let post = |code: CGKeyCode, down: bool, flags: CGEventFlags| -> Result<()> {
        let ev = CGEvent::new_keyboard_event(source()?, code, down)
            .map_err(|_| PlatformError::Failed("couldn't create key event".into()))?;
        ev.set_flags(flags);
        ev.set_integer_value_field(EventField::EVENT_SOURCE_USER_DATA, INJECTED_TAG);
        ev.post(CGEventTapLocation::HID);
        std::thread::sleep(KEY_GAP);
        Ok(())
    };
    // Modifiers go down one by one, each adding its flag.
    let mut held = CGEventFlags::CGEventFlagNull;
    for (code, flag) in &modifiers {
        held |= *flag;
        post(*code, true, held)?;
    }
    post(key, true, flags)?;
    post(key, false, flags)?;
    for (code, flag) in modifiers.iter().rev() {
        held.remove(*flag);
        post(*code, false, held)?;
    }
    Ok(())
}

/// The user's clipboard, waiting to be put back after a paste.
struct PendingRestore {
    saved: Snapshot,
    /// The pasteboard's change count right after our text went on it.
    ours: isize,
    /// Which paste this is; only that paste's timer restores it.
    paste: u64,
}

static PASTES: AtomicU64 = AtomicU64::new(0);

// SAFETY: the snapshot holds immutable NSString/NSData objects, which are
// safe to use from any thread; the pasteboard itself is fetched afresh on
// the restoring thread.
unsafe impl Send for PendingRestore {}

static PENDING_RESTORE: Mutex<Option<PendingRestore>> = Mutex::new(None);

pub(crate) fn paste_text(text: &str) -> Result<()> {
    let pb = general();
    // A paste moments ago may not have put the user's clipboard back yet:
    // that's the one to restore, not our earlier text.
    let pending = PENDING_RESTORE
        .lock()
        .unwrap_or_else(|e| e.into_inner())
        .take()
        .filter(|p| p.ours == pb.changeCount());
    let saved = pending.map_or_else(|| snapshot(&pb), |p| p.saved);
    if !write_text(&pb, text, true) {
        return Err(PlatformError::Failed(
            "couldn't write to the clipboard".into(),
        ));
    }
    let ours = pb.changeCount();
    post_key(
        KEY_V.load(Ordering::Relaxed),
        CGEventFlags::CGEventFlagCommand,
    )?;
    std::thread::sleep(PASTE_SETTLE);
    // Some apps (Chrome under load) read the clipboard well after ⌘V, so
    // the user's clipboard goes back later, in the background, and only if
    // nobody (the user, another app) changed it meanwhile.
    let paste = PASTES.fetch_add(1, Ordering::Relaxed) + 1;
    *PENDING_RESTORE.lock().unwrap_or_else(|e| e.into_inner()) =
        Some(PendingRestore { saved, ours, paste });
    std::thread::spawn(move || {
        std::thread::sleep(RESTORE_AFTER);
        let mut slot = PENDING_RESTORE.lock().unwrap_or_else(|e| e.into_inner());
        // A later paste took over the restore.
        if slot.as_ref().is_none_or(|p| p.paste != paste) {
            return;
        }
        let pending = slot.take().expect("checked above");
        drop(slot);
        let pb = general();
        if pb.changeCount() == pending.ours {
            restore(&pb, &pending.saved);
        }
    });
    Ok(())
}

pub(crate) fn press(action: crate::KeyAction) -> Result<()> {
    match action {
        crate::KeyAction::Return => post_key(KEY_RETURN, CGEventFlags::CGEventFlagNull),
        crate::KeyAction::Undo => post_key(
            KEY_Z.load(Ordering::Relaxed),
            CGEventFlags::CGEventFlagCommand,
        ),
        crate::KeyAction::Backspace => post_key(KEY_DELETE, CGEventFlags::CGEventFlagNull),
        crate::KeyAction::DeleteWord => post_key(KEY_DELETE, CGEventFlags::CGEventFlagAlternate),
        crate::KeyAction::Bold => post_key(
            KEY_B.load(Ordering::Relaxed),
            CGEventFlags::CGEventFlagCommand,
        ),
        crate::KeyAction::Italic => post_key(
            KEY_I.load(Ordering::Relaxed),
            CGEventFlags::CGEventFlagCommand,
        ),
        crate::KeyAction::Right => post_key(KEY_RIGHT, CGEventFlags::CGEventFlagNull),
    }
}

pub(crate) fn type_text(text: &str, soft_breaks: bool) -> Result<()> {
    let line_break = if soft_breaks {
        CGEventFlags::CGEventFlagShift
    } else {
        CGEventFlags::CGEventFlagNull
    };
    for (i, line) in text.split('\n').enumerate() {
        if i > 0 {
            post_key(KEY_RETURN, line_break)?;
        }
        let units: Vec<u16> = line.encode_utf16().collect();
        // CGEventKeyboardSetUnicodeString handles at most 20 UTF-16 units
        // per event. (A surrogate pair split across chunks is rare enough
        // to accept for this fallback path.)
        for chunk in units.chunks(20) {
            for down in [true, false] {
                let ev = CGEvent::new_keyboard_event(source()?, 0, down)
                    .map_err(|_| PlatformError::Failed("couldn't create key event".into()))?;
                ev.set_flags(CGEventFlags::CGEventFlagNull);
                ev.set_string_from_utf16_unchecked(chunk);
                ev.set_integer_value_field(EventField::EVENT_SOURCE_USER_DATA, INJECTED_TAG);
                ev.post(CGEventTapLocation::HID);
            }
            // Give the target app time to consume each chunk in order.
            std::thread::sleep(Duration::from_millis(4));
        }
    }
    Ok(())
}

pub(crate) fn copy_to_clipboard(text: &str) -> Result<()> {
    if write_text(&general(), text, false) {
        Ok(())
    } else {
        Err(PlatformError::Failed(
            "couldn't write to the clipboard".into(),
        ))
    }
}

pub(crate) fn copy_selection() -> Option<String> {
    let pb = general();
    let saved = snapshot(&pb);
    let sentinel = format!("splashdown-copy-probe-{}", std::process::id());
    write_text(&pb, &sentinel, true);
    let before = pb.changeCount();

    post_key(
        KEY_C.load(Ordering::Relaxed),
        CGEventFlags::CGEventFlagCommand,
    )
    .ok()?;
    let started = Instant::now();
    let mut copied = None;
    while started.elapsed() < COPY_TIMEOUT {
        std::thread::sleep(Duration::from_millis(10));
        if pb.changeCount() != before {
            copied = read_text(&pb);
            break;
        }
    }
    restore(&pb, &saved);
    copied.filter(|s| !s.is_empty() && *s != sentinel)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Uses a private pasteboard so the user's clipboard is never touched.
    #[test]
    fn snapshot_and_restore_round_trip() {
        let pb = NSPasteboard::pasteboardWithUniqueName();
        write_text(&pb, "original", false);
        let custom = NSString::from_str("app.splashdown.test");
        pb.setData_forType(Some(&NSData::with_bytes(b"\x01\x02")), &custom);
        let saved = snapshot(&pb);

        write_text(&pb, "temporary", true);
        assert_eq!(read_text(&pb).as_deref(), Some("temporary"));
        let types = pb.types().unwrap();
        assert!(types.iter().any(|t| t.to_string() == TRANSIENT_TYPES[0]));

        restore(&pb, &saved);
        assert_eq!(read_text(&pb).as_deref(), Some("original"));
        assert_eq!(
            pb.dataForType(&custom).map(|d| d.to_vec()),
            Some(vec![1, 2])
        );
    }
}
